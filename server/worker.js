async function signals(env) {
  const items = [];
  // Politico Congress RSS (permitted; check your organization's licensing for full-text use).
  try {
    const rss = await fetch('https://rss.politico.com/congress.xml').then(r => r.text());
    for (const m of rss.matchAll(/<item>[\s\S]*?<title>(?:<!\[CDATA\[)?(.*?)(?:\]\]>)?<\/title>[\s\S]*?<link>(.*?)<\/link>[\s\S]*?<\/item>/g)) {
      if (/clarity|crypto|market structure|senate floor|cloture/i.test(m[1]))
        items.push({ source: 'Politico', title: m[1], url: m[2] });
    }
  } catch (_) { /* feed unavailable — degrade gracefully */ }
  const social = await fetchSocialSignals(env);
  return json({ items: items.slice(0, 10), social, fetched: new Date().toISOString() });
}

